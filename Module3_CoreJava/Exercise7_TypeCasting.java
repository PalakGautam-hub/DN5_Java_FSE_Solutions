// Exercise 7: Type Casting Example

public class Exercise7_TypeCasting {

    public static void main(String[] args) {

        double d = 25.89;

        int n = (int)d;

        System.out.println(
                "Double to Int = " + n
        );

        int x = 50;

        double y = (double)x;

        System.out.println(
                "Int to Double = " + y
        );

    }
}